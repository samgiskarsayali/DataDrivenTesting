package javaPackage;

public class RelationalOperator1 {

	public static void main(String[] args) {
		
		String s = "Selenium";
		String g = "Selenium";
		
		if(s.equalsIgnoreCase(g)) {
			System.out.println("s == g");
		}
		else {
			System.out.println("s != g");
		}
		
		
		int f = 5;
		int h = 15;
		
		if(f == h) {
			System.out.println("f and h are same");
		}
		else {
			System.out.println("f and h are different");
		}
		
		
		
		String a = "Selenium";
		String b = "Automation";
		
		if(a.equalsIgnoreCase(b)) {
			System.out.println("a == b");
		}
		else {
			System.out.println("a != b");
		}
		
		

	}

}
