package javaPackage;

public class Loop3 {

	public static void main(String[] args) {
		
		/* 		Syntax
		 *  while(condition){
		 *  		executable code 
		 *  }
		 */
		
		
		//Print values from 10 to 15 using while Loop
		//To terminate the infinite loop, right click on the console and select Terminate/Disconnect all.
		int a = 1;
		
		while(a <= 5) {
			System.out.println(a);
			a++;
		}

	}

}
