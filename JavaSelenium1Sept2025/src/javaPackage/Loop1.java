package javaPackage;

public class Loop1 {

	public static void main(String[] args) {
		
		//Print the number from 0 to 5
		
		for(int i = 0; i <= 5; i++) {
			System.out.println(i);
		}
		
		
		//Print the number from 10 to 20
		
		for(int a = 10; a <= 20; a++) {
			System.out.println(a);
		}
		
		
		//Print 1,3,5,7,9
		
		for(int q = 1; q < 10; q += 2) {
			System.out.println(q);
		}
		
		
		//Print 10,8,6,4,2
		
		for(int i = 10; i >= 2; i -= 2) {
			System.out.println(i);
		}

	}

}
