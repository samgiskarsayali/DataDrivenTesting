package javaPackage;

public class TypeCastingWidening {
	

	public static void main(String[] args) {
		
		int a = 5; //Local 
		
		//int to double
		
		double b = a;
		
		System.out.println(a); //int variable =>5
		System.out.println(b); //int coverted to double variable =>5.0
		

	}

}
