package javaPackage;

public class AssignmentOperator1 {

	public static void main(String[] args) {
		 int a = 10;
		 
		 a += 15;  
		 System.out.println(a); //25
		 
		 a -= 5;
		 System.out.println(a); //20
		 
		 a *= 3;
		 System.out.println(a); //60
		 
		 a /= 2;
		 System.out.println(a); //30

	}

}
