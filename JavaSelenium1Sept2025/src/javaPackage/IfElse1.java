package javaPackage;

public class IfElse1 {

	public static void main(String[] args) {
		
		//As the condition is true , if block gets executed.
		int a = 15;
		
		if(a > 10) {
			System.out.println("a>10");
		}
		
		//As the condition is false if block won't get executed, and no output will get printed.
		int b = 5;
		
		if(b > 10) {
			System.out.println("b>10");
		}
		

	}

}
